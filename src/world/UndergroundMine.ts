import * as THREE from 'three';
import { terrainHeight } from './Terrain';

// Single authoritative navigation corridor. Positive Z is the surface entrance.
export const MINE_X = 53;
export const MINE_ENTRANCE_Z = -32;
export const MINE_LENGTH = 46;
export const MINE_HALF_WIDTH = 1.55;
const surface = terrainHeight(MINE_X, MINE_ENTRANCE_Z);
const descentLength = 16;
const descentDepth = 7;

export function mineDistance(z: number) { return MINE_ENTRANCE_Z - z; }
export function mineFloorAtDistance(d: number) {
  return surface - descentDepth * THREE.MathUtils.clamp(d / descentLength, 0, 1);
}
export function mineFloorHeight(x: number, z: number): number | null {
  const d = mineDistance(z);
  if (d < 0 || d > MINE_LENGTH || Math.abs(x - MINE_X) > MINE_HALF_WIDTH) return null;
  return mineFloorAtDistance(d);
}
/**
 * Simple deterministic capsule-center constraint for the mine's central aisle.
 * Prevents walking through side walls and the closed end while preserving
 * free movement on the open terrain outside the portal.
 */
export function mineAllowsMovement(fromX: number, fromZ: number, toX: number, toZ: number): boolean {
  const radius = 0.35;
  const halfAisle = MINE_HALF_WIDTH - radius;
  const d0 = mineDistance(fromZ);
  const d1 = mineDistance(toZ);
  const lateral0 = Math.abs(fromX - MINE_X);
  const lateral1 = Math.abs(toX - MINE_X);
  const inside = d0 >= 0 && d0 <= MINE_LENGTH && lateral0 <= MINE_HALF_WIDTH;
  const entering = d1 >= 0 && d1 <= MINE_LENGTH && lateral1 <= MINE_HALF_WIDTH;

  if (inside) {
    // A capsule may leave only through the front portal, not through side
    // walls or the sealed end of the shaft.
    if (lateral1 > halfAisle) return false;
    if (d1 > MINE_LENGTH - radius) return false;
    return true;
  }

  if (!entering) {
    // Reject steps that cut across a wall and end beyond the opposite side.
    // For short player steps this is uncommon, but prevents tunnelling.
    const minD = Math.min(d0, d1);
    const maxD = Math.max(d0, d1);
    if (maxD < 0 || minD > MINE_LENGTH) return true;
    const deltaX = toX - fromX;
    if (Math.abs(deltaX) < 1e-6) return true;
    for (const wallX of [MINE_X - MINE_HALF_WIDTH, MINE_X + MINE_HALF_WIDTH]) {
      const t = (wallX - fromX) / deltaX;
      if (t > 0 && t < 1) {
        const crossingD = d0 + (d1 - d0) * t;
        if (crossingD >= 0 && crossingD <= MINE_LENGTH) return false;
      }
    }
    return true;
  }

  // Entering from outside must cross the OPEN front portal, never a side
  // wall or the back. Keep the player's radius clear of the side supports.
  if (lateral1 > halfAisle || d1 > MINE_LENGTH - radius) return false;
  if (d0 >= 0) return false;
  const t = d1 === d0 ? 1 : -d0 / (d1 - d0);
  const portalX = fromX + (toX - fromX) * t;
  return Math.abs(portalX - MINE_X) <= halfAisle;
}

export function isMinePortalCutout(x: number, z: number) {
  const d = mineDistance(z);
  // Only the first section is open to the sky; deeper sections are covered.
  return Math.abs(x - MINE_X) < 2.15 && d >= -0.5 && d < 9.5;
}

export function createUndergroundMine(scene: THREE.Scene) {
  const root = new THREE.Group();
  root.name = 'WalkableUndergroundMine';
  const earth = new THREE.MeshStandardMaterial({ color: 0x695643, roughness: 1, side: THREE.DoubleSide });
  const timber = new THREE.MeshStandardMaterial({ color: 0x493321, roughness: 1 });
  const makeBox = (w: number, h: number, d: number, material: THREE.Material, x: number, y: number, z: number) => {
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material);
    mesh.position.set(x, y, z);
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    root.add(mesh);
    return mesh;
  };
  // The actual walkable ramp is one continuous surface, not the triangles
  // generated by Meshy (which can contain rails, closed ends and debris).
  const steps = 92;
  const vertices: number[] = [];
  const indices: number[] = [];
  for (let i = 0; i <= steps; i++) {
    const d = MINE_LENGTH * i / steps;
    const y = mineFloorAtDistance(d);
    vertices.push(MINE_X - MINE_HALF_WIDTH, y, MINE_ENTRANCE_Z - d,
                  MINE_X + MINE_HALF_WIDTH, y, MINE_ENTRANCE_Z - d);
    if (i < steps) {
      const a = i * 2;
      indices.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
    }
  }
  const floorGeo = new THREE.BufferGeometry();
  floorGeo.setAttribute('position', new THREE.Float32BufferAttribute(vertices, 3));
  floorGeo.setIndex(indices);
  floorGeo.computeVertexNormals();
  const floor = new THREE.Mesh(floorGeo, earth);
  floor.receiveShadow = true;
  root.add(floor);

  // Enclose the corridor with short, slope-following stone sections.
  // Unlike the closed Meshy GLBs these never cross the central aisle.
  const rockWall = new THREE.MeshStandardMaterial({
    color: 0x504b45, roughness: 1, side: THREE.DoubleSide,
  });
  for (let i = 0; i < steps; i++) {
    const d0 = MINE_LENGTH * i / steps;
    const d1 = MINE_LENGTH * (i + 1) / steps;
    const mid = (d0 + d1) / 2;
    const floor0 = mineFloorAtDistance(d0);
    const floor1 = mineFloorAtDistance(d1);
    const floorY = (floor0 + floor1) / 2;
    const segmentLength = d1 - d0 + 0.025;
    const z = MINE_ENTRANCE_Z - mid;
    if (mid < 17) for (const side of [-1, 1]) {
      // Five shallow display alcoves reveal the original Meshy pieces
      // without placing their unverified geometry across the walking lane.
      const alcoves = [
        { d: 1, side: -1 }, { d: 11, side: 1 },
        { d: 21, side: -1 }, { d: 31, side: 1 },
        { d: 41, side: -1 },
      ];
      const alcove = alcoves.some(item => item.side === side && Math.abs(mid - item.d) < 1.7);
      if (!alcove) {
        makeBox(0.42, 3.05, segmentLength, rockWall,
          MINE_X + side * (MINE_HALF_WIDTH + 0.21), floorY + 1.52, z);
      }
    }
    // At the portal the player sees an open entrance. Begin the ceiling
    // farther down the decline, below the surface instead of above ground.
    if (mid >= 8 && mid < 17) {
      makeBox(MINE_HALF_WIDTH * 2 + 0.9, 0.35, segmentLength,
        rockWall, MINE_X, floorY + 3.12, z);
    }
  }

  // Supports and rails are visuals, not movement colliders.
  for (let d = 4; d < 17; d += 4) {
    const y = mineFloorAtDistance(d);
    const z = MINE_ENTRANCE_Z - d;
    makeBox(.25, 3.2, .3, timber, MINE_X - 1.48, y + 1.6, z);
    makeBox(.25, 3.2, .3, timber, MINE_X + 1.48, y + 1.6, z);
    makeBox(3.2, .27, .35, timber, MINE_X, y + 3.13, z);
  }
  // The flat section's sleepers and rails are provided by Meshy GLBs.
  // Lighting is essential: otherwise a physically underground passage is black.
  for (const d of [7, 17, 28, 39]) {
    const light = new THREE.PointLight(0xffb66a, 8, 12, 2);
    light.position.set(MINE_X, mineFloorAtDistance(d) + 2.6, MINE_ENTRANCE_Z - d);
    root.add(light);
  }
  scene.add(root);
  return root;
}
