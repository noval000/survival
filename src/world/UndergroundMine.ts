import * as THREE from 'three';
import { terrainHeight } from './Terrain';

// Single authoritative navigation corridor. Positive Z is the surface entrance.
export const MINE_X = 53;
export const MINE_ENTRANCE_Z = -32;
export const MINE_LENGTH = 46;
export const MINE_HALF_WIDTH = 1.55;
const surface = terrainHeight(MINE_X, MINE_ENTRANCE_Z);
const descentLength = 16;
const descentDepth = 7;

export function mineDistance(z: number) { return MINE_ENTRANCE_Z - z; }
export function mineFloorAtDistance(d: number) {
  return surface - descentDepth * THREE.MathUtils.clamp(d / descentLength, 0, 1);
}
export function mineFloorHeight(x: number, z: number): number | null {
  const d = mineDistance(z);
  if (d < 0 || d > MINE_LENGTH || Math.abs(x - MINE_X) > MINE_HALF_WIDTH) return null;
  return mineFloorAtDistance(d);
}
export function isMinePortalCutout(x: number, z: number) {
  const d = mineDistance(z);
  // Only the first section is open to the sky; deeper sections are covered.
  return Math.abs(x - MINE_X) < 2.15 && d >= -0.5 && d < 9.5;
}

export function createUndergroundMine(scene: THREE.Scene) {
  const root = new THREE.Group();
  root.name = 'WalkableUndergroundMine';
  const stone = new THREE.MeshStandardMaterial({ color: 0x514d49, roughness: 1, side: THREE.DoubleSide });
  const earth = new THREE.MeshStandardMaterial({ color: 0x695643, roughness: 1, side: THREE.DoubleSide });
  const timber = new THREE.MeshStandardMaterial({ color: 0x493321, roughness: 1 });
  const metal = new THREE.MeshStandardMaterial({ color: 0x665f59, metalness: 0.6, roughness: 0.65 });
  const makeBox = (w: number, h: number, d: number, material: THREE.Material, x: number, y: number, z: number) => {
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), material);
    mesh.position.set(x, y, z);
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    root.add(mesh);
    return mesh;
  };
  // The actual walkable ramp is one continuous surface, not the triangles
  // generated by Meshy (which can contain rails, closed ends and debris).
  const steps = 92;
  const vertices: number[] = [];
  const indices: number[] = [];
  for (let i = 0; i <= steps; i++) {
    const d = MINE_LENGTH * i / steps;
    const y = mineFloorAtDistance(d);
    vertices.push(MINE_X - MINE_HALF_WIDTH, y, MINE_ENTRANCE_Z - d,
                  MINE_X + MINE_HALF_WIDTH, y, MINE_ENTRANCE_Z - d);
    if (i < steps) {
      const a = i * 2;
      indices.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
    }
  }
  const floorGeo = new THREE.BufferGeometry();
  floorGeo.setAttribute('position', new THREE.Float32BufferAttribute(vertices, 3));
  floorGeo.setIndex(indices);
  floorGeo.computeVertexNormals();
  const floor = new THREE.Mesh(floorGeo, earth);
  floor.receiveShadow = true;
  root.add(floor);

  // Walls/roof follow the same slope as the navigation floor. Sections
  // extend underground; no tunnel pieces are placed on the terrain surface.
  for (let i = 0; i < steps; i++) {
    const d0 = MINE_LENGTH * i / steps;
    const d1 = MINE_LENGTH * (i + 1) / steps;
    const mid = (d0 + d1) / 2;
    const y0 = mineFloorAtDistance(d0);
    const y1 = mineFloorAtDistance(d1);
    const slope = Math.atan2(y0 - y1, d1 - d0);
    const centerY = (y0 + y1) / 2;
    const centerZ = MINE_ENTRANCE_Z - mid;
    // Do not render placeholder box walls/roof over the real Meshy GLBs.
    // The terrain cap and loaded GLB sections provide the visual enclosure.
    void slope;
    void centerY;
    void centerZ;
  }

  // Supports and rails are visuals, not movement colliders.
  for (let d = 0; d <= MINE_LENGTH; d += 4) {
    const y = mineFloorAtDistance(d);
    const z = MINE_ENTRANCE_Z - d;
    makeBox(.25, 3.2, .3, timber, MINE_X - 1.48, y + 1.6, z);
    makeBox(.25, 3.2, .3, timber, MINE_X + 1.48, y + 1.6, z);
    makeBox(3.2, .27, .35, timber, MINE_X, y + 3.13, z);
  }
  for (let d = 17; d < MINE_LENGTH; d += 1.2) {
    const y = mineFloorAtDistance(d);
    const z = MINE_ENTRANCE_Z - d;
    makeBox(1.55, .1, .18, timber, MINE_X, y + .07, z);
  }
  for (const offset of [-.55, .55]) {
    makeBox(.09, .1, MINE_LENGTH - 17, metal, MINE_X + offset,
      mineFloorAtDistance(20) + .13, MINE_ENTRANCE_Z - (MINE_LENGTH + 17) / 2);
  }
  // Lighting is essential: otherwise a physically underground passage is black.
  for (const d of [7, 17, 28, 39]) {
    const light = new THREE.PointLight(0xffb66a, 8, 12, 2);
    light.position.set(MINE_X, mineFloorAtDistance(d) + 2.6, MINE_ENTRANCE_Z - d);
    root.add(light);
  }
  scene.add(root);
  return root;
}
